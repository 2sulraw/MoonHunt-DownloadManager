// ─── Cancelled GID registry ──────────────────────────────────────
// When a user cancels a download, the GID is added here so the poller
// can filter it out of snapshots (preventing cancelled downloads from
// re-appearing as "complete" or "error").

type CancelledSet = Arc<Mutex<HashSet<String>>>;
static CANCELLED: OnceLock<CancelledSet> = OnceLock::new();

fn cancelled_registry() -> &'static CancelledSet {
    CANCELLED.get_or_init(|| Arc::new(Mutex::new(HashSet::new())))
}

/// Mark a GID as cancelled.
pub fn mark_cancelled(gid: &str) {
    if let Ok(mut set) = cancelled_registry().lock() {
        set.insert(gid.to_string());
    }
}

/// Get the list of cancelled GIDs (used to filter UI snapshots).
pub fn cancelled_gids() -> Vec<String> {
    cancelled_registry()
        .lock()
        .map(|s| s.iter().cloned().collect())
        .unwrap_or_default()
}

// ─── Dedup registry ──────────────────────────────────────────────
// Chrome can fire the download event twice for a single user action.
// Reject duplicate POST /download requests for the same URL within a
// short window so they never reach the pending queue.

type RecentDownloads = Arc<Mutex<HashMap<String, Instant>>>;
static RECENT: OnceLock<RecentDownloads> = OnceLock::new();

fn recent_downloads() -> &'static RecentDownloads {
    RECENT.get_or_init(|| Arc::new(Mutex::new(HashMap::new())))
}

pub fn write_netscape_cookies(cookies: &[ExtensionCookie]) -> Result<String, String> {
    use std::fs;
    let mut path = std::env::temp_dir();
    path.push("moonhunt_cookies.txt");

    let mut lines = vec![
        "# Netscape HTTP Cookie File".to_string(),
        "# Generated by MoonHunt extension — do not edit.".to_string(),
    ];
    for c in cookies {
        let domain = if c.domain.starts_with('.') {
            c.domain.clone()
        } else {
            format!(".{}", c.domain)
        };
        let flag = "TRUE";
        let cpath = if c.path.is_empty() { "/".to_string() } else { c.path.clone() };
        let secure = if c.secure { "TRUE" } else { "FALSE" };
        let expires = c.expires
            .map(|e| if e > 0.0 { format!("{}", e as i64) } else { "0".to_string() })
            .unwrap_or_else(|| "0".to_string());
        // Netscape format: domain TAB flag TAB path TAB secure TAB expires TAB name TAB value
        lines.push(format!("{}\t{}\t{}\t{}\t{}\t{}\t{}", domain, flag, cpath, secure, expires, c.name, c.value));
    }
    fs::write(&path, lines.join("\n"))
        .map_err(|e| format!("Failed to write cookies: {}", e))?;
    Ok(path.to_string_lossy().to_string())
}

#[command]
pub async fn set_extension_settings(
    settings: ExtensionSettings,
    app: tauri::AppHandle,
) -> Result<String, String> {
    let state = app.state::<AppState>();
    let mut guard = lock(&state.extension_settings)?;
    *guard = settings;
    Ok("Extension settings saved".to_string())
}

#[command]
pub async fn open_chrome_extensions() -> Result<String, String> {
    use std::path::PathBuf;
    let mut chrome_paths = vec![
        PathBuf::from("C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe"),
        PathBuf::from("C:\\Program Files (x86)\\Google\\Chrome\\Application\\chrome.exe"),
    ];

    if let Ok(local_app_data) = std::env::var("LOCALAPPDATA") {
        chrome_paths.push(
            PathBuf::from(local_app_data)
                .join("Google")
                .join("Chrome")
                .join("Application")
                .join("chrome.exe"),
        );
    }

    for chrome_path in chrome_paths {
        if chrome_path.exists() {
            cmd_no_window(&chrome_path.to_string_lossy())
                .arg("--profile-directory=Default")
                .arg("--new-window")
                .arg("chrome://extensions")
                .spawn()
                .map_err(|e| format!("Failed to open Chrome Extensions page: {}", e))?;
            return Ok("Opened Chrome Extensions page in Chrome".to_string());
        }
    }

    cmd_no_window("cmd")
        .args([
            "/C",
            "start",
            "",
            "chrome",
            "--profile-directory=Default",
            "--new-window",
            "chrome://extensions",
        ])
        .spawn()
        .map_err(|e| {
            format!(
                "Chrome executable not found and Windows fallback failed: {}",
                e
            )
        })?;

    Ok("Opened Chrome Extensions page".to_string())
}


// When extension auth is enabled, accept the request only if it carries a
// matching token via `X-MoonHunt-Token: <token>` or `Authorization: Bearer <token>`.
fn request_has_valid_token(request: &str, settings: &ExtensionSettings) -> bool {
    if !settings.extension_auth_enabled {
        return true;
    }
    let expected = settings.extension_auth_token.trim();
    if expected.is_empty() {
        return false;
    }
    let body_start = request.find("\r\n\r\n").unwrap_or(request.len());
    for line in request[..body_start].lines() {
        let Some((key, value)) = line.split_once(':') else {
            continue;
        };
        let key = key.trim().to_ascii_lowercase();
        if key == "x-moonhunt-token" && value.trim() == expected {
            return true;
        }
        if key == "authorization" {
            let value = value.trim();
            let bearer = value
                .strip_prefix("Bearer ")
                .or_else(|| value.strip_prefix("bearer "))
                .map(str::trim);
            if bearer == Some(expected) {
                return true;
            }
        }
    }
    false
}

// Start the HTTP server for extension communication

pub fn start_http_server(
// Start local HTTP server for browser extension communication.
    pending_downloads: Arc<Mutex<Vec<PendingDownload>>>,
    extension_settings: Arc<Mutex<ExtensionSettings>>,
    app_handle: tauri::AppHandle,
) {
    let port = {
        let settings = extension_settings.lock().unwrap_or_else(|e| e.into_inner());
        settings.extension_port
    };
    std::thread::spawn(move || {
        let addr = format!("127.0.0.1:{}", port);
        println!("[OK] HTTP server configured for port {}", port);
        if let Ok(listener) = std::net::TcpListener::bind(&addr) {
            println!("[✓] HTTP server listening on http://127.0.0.1:{}", port);

            for stream in listener.incoming() {
                let pending = pending_downloads.clone();
                let extension_settings = extension_settings.clone();
                let app_handle = app_handle.clone();

                std::thread::spawn(move || {
                    if let Ok(mut stream) = stream {
                        use std::io::{Read, Write};

                        let mut buffer: Vec<u8> = Vec::new();
                        let mut temp = [0u8; 4096];
                        // Read until headers + body (if Content-Length provided) are fully received
                        loop {
                            match stream.read(&mut temp) {
                                Ok(0) => break, // connection closed
                                Ok(n) => {
                                    buffer.extend_from_slice(&temp[..n]);
                                    // check if we have headers end
                                    if let Some(headers_end_pos) = buffer.windows(4).position(|w| w == b"\r\n\r\n") {
                                        // try to parse Content-Length
                                        let headers = String::from_utf8_lossy(&buffer[..headers_end_pos]).to_string();
                                        let mut content_length: Option<usize> = None;
                                        for line in headers.lines() {
                                            if let Some(idx) = line.to_lowercase().find("content-length:") {
                                                let val = line[idx + "content-length:".len()..].trim();
                                                if let Ok(v) = val.parse::<usize>() {
                                                    content_length = Some(v);
                                                    break;
                                                }
                                            }
                                        }

                                        let total_needed = headers_end_pos + 4 + content_length.unwrap_or(0);
                                        if buffer.len() >= total_needed || content_length.is_none() {
                                            break;
                                        }
                                        // else continue reading until we have full body
                                    }
                                    // If headers not yet received, continue reading
                                    if buffer.len() > 1024 * 64 {
                                        // avoid infinite reads on malformed input
                                        break;
                                    }
                                    continue;
                                }
                                Err(_) => break,
                            }
                        }

                        let request = String::from_utf8_lossy(&buffer).to_string();

                        if request.starts_with("GET /api/ping") {
                            let ext_settings = extension_settings.lock().unwrap_or_else(|e| e.into_inner()).clone();
                            if !request_has_valid_token(&request, &ext_settings) {
                                let response = "HTTP/1.1 401 Unauthorized\r\nContent-Length: 0\r\n\r\n";
                                let _ = stream.write_all(response.as_bytes());
                            } else {
                            let body = serde_json::to_string(&json!({"status": "ok", "version": env!("CARGO_PKG_VERSION")})).unwrap_or_default();
                            let response = format!(
                                "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nAccess-Control-Allow-Origin: *\r\nContent-Length: {}\r\n\r\n{}",
                                body.len(), body
                            );
                            let _ = stream.write_all(response.as_bytes());
                            }
                        } else if request.starts_with("GET /extension-config") {
                            let settings = extension_settings.lock().unwrap_or_else(|e| e.into_inner()).clone();

                            // return only what extension needs, not full settings. The token is never
                            // served to the browser — the user must type it in the
                            // extension manually, so a wrong/empty token is rejected.
                            let response_obj = json!({
                                "extensionPort": settings.extension_port,
                                "authRequired": settings.extension_auth_enabled,
                                "protocolEnabled": settings.open_in_browser_protocol_enabled,
                            });
                            let body = serde_json::to_string(&response_obj)
                                .unwrap_or_else(|_| "{}".to_string());
                            let response = format!(
                                "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nAccess-Control-Allow-Origin: *\r\nContent-Length: {}\r\n\r\n{}",
                                body.len(),
                                body
                            );
                            let _ = stream.write_all(response.as_bytes());
                        } else if request.starts_with("GET /focus") {
                            // Bring the main window to the front. The extension calls
                            // this over HTTP (no browser protocol prompt involved) so
                            // "Open MoonHunt" reliably focuses the running app.
                            let app = app_handle.clone();
                            std::thread::spawn(move || {
                                if let Some(window) = app.get_webview_window("main") {
                                    let _ = window.unminimize();
                                    let _ = window.show();
                                    let _ = window.set_focus();
                                }
                            });
                            let body = "{\"status\":\"ok\"}";
                            let response = format!(
                                "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nAccess-Control-Allow-Origin: *\r\nContent-Length: {}\r\n\r\n{}",
                                body.len(),
                                body
                            );
                            let _ = stream.write_all(response.as_bytes());
                        } else if request.contains("POST /download") {
                            let ext_settings = extension_settings.lock().unwrap_or_else(|e| e.into_inner()).clone();
                            if !request_has_valid_token(&request, &ext_settings) {
                                let response = "HTTP/1.1 401 Unauthorized\r\nContent-Length: 0\r\n\r\n";
                                let _ = stream.write_all(response.as_bytes());
                            } else {
                            // More robust body extraction: prefer exact Content-Length when present
                            if let Some(body_start) = request.find("\r\n\r\n") {
                                let headers_part = &request[..body_start];
                                let mut content_length: Option<usize> = None;
                                for line in headers_part.lines() {
                                    let lower = line.to_lowercase();
                                    if let Some(idx) = lower.find("content-length:") {
                                        if let Ok(v) = line[idx + "content-length:".len()..].trim().parse::<usize>() {
                                            content_length = Some(v);
                                            break;
                                        }
                                    }
                                }

                                let raw_body = &request[body_start + 4..];
                                let body = if let Some(len) = content_length {
                                    // Take at most the declared length (handles extra data after body)
                                    &raw_body[..raw_body.len().min(len)]
                                } else {
                                    raw_body
                                };

                                // Try to parse the JSON body reliably (trim only safe whitespace)
                                let trimmed = body.trim_matches(|c: char| c.is_whitespace() || c == '\0');
                                println!("[HTTP] Raw body ({} bytes): {}", trimmed.len(), if trimmed.len() > 500 { &trimmed[..500] } else { trimmed });
                                if let Ok(download) = serde_json::from_str::<PendingDownload>(trimmed) {
                                    println!(
                                        "[HTTP] POST /download: url={}, filename={}, headers={:?}",
                                        download.url, download.filename, download.headers
                                    );

                                    // Dedup: Chrome can fire the download event twice for
                                    // a single click. Drop duplicates within 5 seconds.
                                    let is_dup = {
                                        let mut recent = recent_downloads().lock().unwrap_or_else(|e| e.into_inner());
                                        let now = Instant::now();
                                        recent.retain(|_, t| now.duration_since(*t).as_secs() < 5);
                                        // Cap map size so stale entries can't grow unbounded.
                                        if recent.len() >= 1000 {
                                            recent.clear();
                                        }
                                        if recent.contains_key(&download.url) {
                                            true
                                        } else {
                                            recent.insert(download.url.clone(), now);
                                            false
                                        }
                                    };

                                    if !is_dup {
                                        {
                                            let mut guard = pending.lock().unwrap_or_else(|e| e.into_inner());
                                            guard.push(download.clone());
                                        }
                                        let _ = app_handle.emit("pending-download", &download);

                                        {
                                            let app = app_handle.clone();
                                            std::thread::spawn(move || {
                                                if let Some(window) = app.get_webview_window("main") {
                                                    let _ = window.unminimize();
                                                    let _ = window.show();
                                                    let _ = window.set_focus();
                                                }
                                            });
                                        }
                                    } else {
                                        println!("[HTTP] POST /download: duplicate suppressed for {}", download.url);
                                    }

                                    let response = "HTTP/1.1 200 OK\r\nContent-Length: 2\r\n\r\nOK";
                                    let _ = stream.write_all(response.as_bytes());
                                } else {
                                    let response = "HTTP/1.1 400 Bad Request\r\nContent-Length: 0\r\n\r\n";
                                    let _ = stream.write_all(response.as_bytes());
                                }
                            } else {
                                let response = "HTTP/1.1 400 Bad Request\r\nContent-Length: 0\r\n\r\n";
                                let _ = stream.write_all(response.as_bytes());
                            }
                            }
                        } else if request.contains("POST /save-cookies") {
                            let ext_settings = extension_settings.lock().unwrap_or_else(|e| e.into_inner()).clone();
                            if !request_has_valid_token(&request, &ext_settings) {
                                let response = "HTTP/1.1 401 Unauthorized\r\nContent-Length: 0\r\n\r\n";
                                let _ = stream.write_all(response.as_bytes());
                            } else {
                            if let Some(body_start) = request.find("\r\n\r\n") {
                                let body = &request[body_start + 4..];
                                #[derive(serde::Deserialize)]
                                struct CookiePayload { cookies: Vec<ExtensionCookie> }
                                if let Ok(payload) = serde_json::from_str::<CookiePayload>(body.trim()) {
                                    let count = payload.cookies.len();
                                    match write_netscape_cookies(&payload.cookies) {
                                        Ok(path) => {
                                            println!("[🍪] Extension exported {} cookies → {}", count, path);
                                            let resp_body = serde_json::json!({"ok": true, "count": count, "path": path});
                                            let resp = serde_json::to_string(&resp_body).unwrap_or_default();
                                            let response = format!("HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nAccess-Control-Allow-Origin: *\r\nContent-Length: {}\r\n\r\n{}", resp.len(), resp);
                                            let _ = stream.write_all(response.as_bytes());
                                        }
                                        Err(e) => {
                                            eprintln!("[✗] Cookie save failed: {}", e);
                                            let response = "HTTP/1.1 500 Internal Server Error\r\nContent-Length: 0\r\n\r\n";
                                            let _ = stream.write_all(response.as_bytes());
                                        }
                                    }
                                } else {
                                    let response = "HTTP/1.1 400 Bad Request\r\nContent-Length: 0\r\n\r\n";
                                    let _ = stream.write_all(response.as_bytes());
                                }
                            } else {
                                let response = "HTTP/1.1 400 Bad Request\r\nContent-Length: 0\r\n\r\n";
                                let _ = stream.write_all(response.as_bytes());
                            }
                            }
                        } else if request.starts_with("OPTIONS /extension-config") || request.starts_with("OPTIONS /save-cookies") || request.starts_with("OPTIONS /download") {
                            let response = "HTTP/1.1 204 No Content\r\nAccess-Control-Allow-Origin: *\r\nAccess-Control-Allow-Methods: GET, POST, OPTIONS\r\nAccess-Control-Allow-Headers: Content-Type, X-MoonHunt-Token, Authorization\r\nContent-Length: 0\r\n\r\n";
                            let _ = stream.write_all(response.as_bytes());
                        } else {
                            let response = "HTTP/1.1 404 Not Found\r\nContent-Length: 0\r\n\r\n";
                            let _ = stream.write_all(response.as_bytes());
                        }
                    }
                });
            }
        } else {
            eprintln!("[✗] Failed to bind HTTP server on port {}", port);
        }
    });
}
