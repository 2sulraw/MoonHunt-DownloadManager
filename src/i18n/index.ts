export type LocaleCode = 'en' | 'fr' | 'fa' | 'es' | 'pt' | 'ru' | 'ja' | 'zh' | 'ar'

export interface LocaleInfo {
  code: LocaleCode
  label: string
  dir: 'ltr' | 'rtl'
}

export const LOCALES: LocaleInfo[] = [
  { code: 'en', label: 'English', dir: 'ltr' },
  { code: 'fa', label: 'فارسی', dir: 'ltr' },
  { code: 'fr', label: 'Français', dir: 'ltr' },
  { code: 'es', label: 'Español', dir: 'ltr' },
  { code: 'pt', label: 'Português', dir: 'ltr' },
  { code: 'ru', label: 'Русский', dir: 'ltr' },
  { code: 'ja', label: '日本語', dir: 'ltr' },
  { code: 'zh', label: '中文', dir: 'ltr' },
  { code: 'ar', label: 'العربية', dir: 'ltr' },
]

export function isLocaleCode(value: string): value is LocaleCode {
  return LOCALES.some((l) => l.code === value)
}

export function normalizeLocale(value: string | null | undefined): LocaleCode {
  return value && isLocaleCode(value) ? value : 'en'
}

