export const messages: Record<LocaleCode, Messages> = {
  en,
  fr: { ...fr, ...frExtras, ...frMissing },
  fa: { ...fa, ...faExtras, ...faMissing },
  es: { ...es, ...esExtras, ...esMissing },
  pt: { ...pt, ...ptExtras, ...ptMissing },
  ru: { ...ru, ...ruExtras, ...ruMissing },
  ja: { ...ja, ...jaExtras, ...jaMissing },
  zh: { ...zh, ...zhExtras, ...zhMissing },
  ar: { ...ar, ...arExtras, ...arMissing },
}

const STORAGE_KEY = 'moonhunt_locale'

const locale = ref<LocaleCode>(normalizeLocale(localStorage.getItem(STORAGE_KEY)))

const isRtl = computed(() => (LOCALES.find((l) => l.code === locale.value)?.dir ?? 'ltr') === 'rtl')

const RTL_TEXT_RE = /[\u0591-\u07FF\uFB1D-\uFDFD\uFE70-\uFEFC]/
const LATIN_TEXT_RE = /[A-Za-z0-9]/

function isolateMixedBidi(text: string): string {
  // Only RTL/Latin mixtures need an isolate; unmixed translations stay LTR.
  if (locale.value !== 'fa' && locale.value !== 'ar') return text
  if (!RTL_TEXT_RE.test(text) || !LATIN_TEXT_RE.test(text)) return text
  return `\u2067${text}\u2069`
}

function t(key: string): string {
  const table = messages[locale.value]
  return isolateMixedBidi(table?.[key] ?? messages.en[key] ?? key)
}

function applyLocale(code: LocaleCode) {
  locale.value = code
  document.documentElement.lang = code
  document.documentElement.dir = isRtl.value ? 'rtl' : 'ltr'
  localStorage.setItem(STORAGE_KEY, code)
}

export function setLocale(code: LocaleCode) {
  applyLocale(code)
  try {
    void invoke<Settings>('get_all_settings').then((settings) => {
      if (settings) {
        settings.language = code
        void invoke('save_all_settings', { settings })
      }
    })
  } catch {
    // Running outside Tauri; localStorage still persists the locale.
  }
}

async function loadLocale() {
  try {
    const settings = await invoke<Settings>('get_all_settings')
    applyLocale(normalizeLocale(settings?.language || localStorage.getItem(STORAGE_KEY)))
  } catch {
    applyLocale(normalizeLocale(localStorage.getItem(STORAGE_KEY)))
  }
}

export function useI18n() {
  return {
    locale,
    isRtl,
    LOCALES,
    t,
    setLocale,
    loadLocale,
  }
}
