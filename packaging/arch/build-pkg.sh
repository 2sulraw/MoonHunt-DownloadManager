#!/usr/bin/env bash
set -euo pipefail

VER=0.0.7
REL=1
BIN=/home/werlos/moonhunt-src/target/release/moonhunt
ARIA=/mnt/d/MoonHunt/src-tauri/binaries/aria2c-x86_64-unknown-linux-gnu
ICONS=/mnt/d/MoonHunt/src-tauri/icons
LIC=/mnt/d/MoonHunt/LICENSE
OUT=/mnt/d/MoonHunt-Rust/dist
PKG=/tmp/moonhunt-arch
NAME=moonhunt-${VER}-${REL}-x86_64.pkg.tar.xz

rm -rf "$PKG"
mkdir -p "$PKG/usr/bin" \
         "$PKG/usr/lib/moonhunt" \
         "$PKG/usr/share/applications" \
         "$PKG/usr/share/icons/hicolor/32x32/apps" \
         "$PKG/usr/share/icons/hicolor/128x128/apps" \
         "$PKG/usr/share/icons/hicolor/256x256/apps" \
         "$PKG/usr/share/licenses/moonhunt"

install -m 0755 "$BIN"  "$PKG/usr/bin/moonhunt"
install -m 0755 "$ARIA" "$PKG/usr/lib/moonhunt/aria2c"
install -m 0644 "$ICONS/32x32.png"       "$PKG/usr/share/icons/hicolor/32x32/apps/moonhunt.png"
install -m 0644 "$ICONS/128x128.png"     "$PKG/usr/share/icons/hicolor/128x128/apps/moonhunt.png"
install -m 0644 "$ICONS/128x128@2x.png"  "$PKG/usr/share/icons/hicolor/256x256/apps/moonhunt.png"
install -m 0644 "$LIC" "$PKG/usr/share/licenses/moonhunt/LICENSE"

cat > "$PKG/usr/share/applications/moonhunt.desktop" <<'EOF'
[Desktop Entry]
Type=Application
Version=1.0
Name=MoonHunt
GenericName=Download Manager
Comment=MoonHunt download manager
Exec=/usr/bin/moonhunt %U
Icon=moonhunt
Terminal=false
Categories=Network;FileTransfer;Utility;
StartupWMClass=moonhunt
MimeType=x-scheme-handler=moonhunt;
EOF

tr -d '\r' < /mnt/d/MoonHunt-Rust/packaging/arch/moonhunt.install > "$PKG/.INSTALL"
chmod 0644 "$PKG/.INSTALL"

SIZE=$(find "$PKG" -type f -printf '%s\n' | awk '{s+=$1} END {print s+0}')
BUILDDATE=$(date +%s)

cat > "$PKG/.PKGINFO" <<EOF
# Generated by makepkg 6.1.0
pkgname = moonhunt
pkgbase = moonhunt
pkgver = ${VER}-${REL}
pkgdesc = MoonHunt download manager (native Rust/egui)
url = https://github.com/2sulraw/MoonHunt-DownloadManager
builddate = ${BUILDDATE}
packager = MoonHunt Contributors
size = ${SIZE}
arch = x86_64
license = GPL-3.0-only
depend = aria2
depend = openssl
depend = xz
depend = gcc-libs
depend = glibc
depend = libx11
depend = libxkbcommon
depend = libxkbcommon-x11
depend = libxcursor
depend = libxrandr
depend = libxi
depend = libxinerama
depend = mesa
depend = wayland
depend = fontconfig
depend = hicolor-icon-theme
optdepend = yt-dlp: media / YouTube downloads
optdepend = ffmpeg: merge separate video+audio streams
makedepend = rust
makedepend = pkgconf
makedepend = base-devel
install = moonhunt.install
xdata = pkgtype=pkg
EOF
chmod 0644 "$PKG/.PKGINFO"

rm -f "$OUT/$NAME"
tar -C "$PKG" --owner=0 --group=0 --numeric-owner -cJf "$OUT/$NAME" .PKGINFO .INSTALL usr

echo "=== package ==="
ls -l "$OUT/$NAME"
echo "=== .PKGINFO ==="
cat "$PKG/.PKGINFO"
echo "=== tar contents ==="
tar -tJf "$OUT/$NAME"
